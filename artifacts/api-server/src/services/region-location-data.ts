export function getCountrySearchPatterns(countryName: string): string[] {
  return COUNTRY_NAME_MAPPING[countryName] || [countryName];
}

const escapePattern = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** The public location API and SSR must use the same country/city membership. */
export function buildRegionStationScope(countryName: string, citySlug?: string): {
  filter: Record<string, any>; cityName?: string;
} | null {
  const countries = getCountrySearchPatterns(countryName).map(country => ({
    country: { $regex: `^${escapePattern(country)}$`, $options: 'i' },
  }));
  const filter: Record<string, any> = { isListVisible: true, $or: countries };
  if (!citySlug) return { filter };
  const cities = COUNTRY_CITIES[countryName] || [];
  const termsFor = (city: string) => CITY_ALTERNATIVE_NAMES[city] || [city];
  if (citySlug === 'all') {
    const exclude = cities.flatMap(city => termsFor(city).flatMap(term => [
      { name: { $not: { $regex: new RegExp(escapePattern(term), 'i') } } },
      { tags: { $not: { $regex: new RegExp(escapePattern(term), 'i') } } },
    ]));
    if (exclude.length) {
      filter.$and = [{ $or: countries }, { $and: exclude }];
      delete filter.$or;
    }
    return { filter, cityName: 'ALL' };
  }
  const cityName = cities.find(city => city.toLowerCase().replace(/[^a-z0-9]/g, '-')
    .replace(/--+/g, '-').replace(/^-|-$/g, '') === citySlug);
  if (!cityName) return null;
  filter.$and = [{ $or: countries }, { $or: termsFor(cityName).flatMap(term => [
    { name: { $regex: new RegExp(escapePattern(term), 'i') } },
    { tags: { $regex: new RegExp(escapePattern(term), 'i') } },
  ]) }];
  delete filter.$or;
  return { filter, cityName };
}
